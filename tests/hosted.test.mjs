import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import vm from 'node:vm';
const source=JSON.parse(readFileSync('web/library.json','utf8'));
assert.equal(source.items.length,1074);assert.equal(source.items.flatMap(r=>r.media).length,1211);
assert(source.items.every(r=>r.snapshots.length===0&&!('edit' in r)&&r.media.every(m=>m.media_url.startsWith('https://lightroom.adobe.com/v2c/spaces/'))));
const storage=new Map(),blobs=new Map();let counter=0;
const context=vm.createContext({window:{},TextEncoder,Blob,Date,JSON,Error,Uint8Array,DataView,setTimeout:()=>{},fetch:async()=>({ok:true,json:async()=>source}),localStorage:{getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v)},URL:{createObjectURL:b=>{const url='blob:fixture-'+counter++;blobs.set(url,b);return url;},revokeObjectURL:()=>{}}});
vm.runInContext(readFileSync('web/hosted.js','utf8'),context);const api=context.window.mdcHostedAPI;
const id=source.items.find(r=>r.media.length===5).id;
await api('/api/item',{id,revision:0,patch:{title:'Validation fixture',drafts:{LinkedIn:'Reviewed caption'}}});
assert.equal((await api('/api/library')).items.find(r=>r.id===id).edit.drafts.LinkedIn,'Reviewed caption');
await assert.rejects(()=>api('/api/item',{id,revision:0,patch:{title:'Stale'}}),e=>e.status===409);
const result=await api('/api/package',{ids:[id],platforms:['Instagram','Facebook','TikTok','YouTube','LinkedIn']});
writeFileSync('/private/tmp/mdc-hosted-test.zip',Buffer.from(await blobs.get(result.download_url).arrayBuffer()));
console.log('Passed: public data coverage/privacy, browser draft persistence, conflicting revisions, publishing ZIP generation.');
const other=source.items.find(r=>r.id!==id).id;
const created=await api('/api/bundle',{action:'create',name:'  Coastal story  ',ids:[id,id]});
assert.equal(created.bundle.name,'Coastal story');assert.equal(created.bundle.content_ids.length,1);
await api('/api/bundle',{action:'add',id:created.bundle.id,ids:[other,id]});
assert.equal((await api('/api/bundles')).bundles[0].content_ids.length,2);
await api('/api/bundle',{action:'reorder',id:created.bundle.id,ids:[other,id]});
await assert.rejects(()=>api('/api/bundle',{action:'reorder',id:created.bundle.id,ids:[id]}));
await assert.rejects(()=>api('/api/bundle',{action:'create',name:' ',ids:[]}));
await assert.rejects(()=>api('/api/bundle',{action:'add',id:created.bundle.id,ids:['unknown']}));
await api('/api/bundle',{action:'update',id:created.bundle.id,notes:'Keep carousel sequence'});
const persisted=JSON.parse(storage.get('mdc-publishing-workspace-v1'));
assert.equal(persisted.items[id].drafts.LinkedIn,'Reviewed caption');assert.equal(persisted.bundles[created.bundle.id].notes,'Keep carousel sequence');
const bundled=await api('/api/package',{ids:[other,id],platforms:['LinkedIn'],bundle_name:'Coastal story',bundle_notes:'Keep carousel sequence'});
writeFileSync('/private/tmp/mdc-bundle-test.zip',Buffer.from(await blobs.get(bundled.download_url).arrayBuffer()));
await api('/api/bundle',{action:'remove',id:created.bundle.id,ids:[other]});
assert.equal((await api('/api/bundles')).bundles[0].content_ids.length,1);
console.log('Passed: anonymous named bundles, deduplication, reordering validation, notes, legacy draft preservation and bundle packages.');
